BASE = [0, 3, 1, 4, 1, 5]      # 1-indexed，原数组是 [3, 1, 4, 1, 5]

CHECKS = [
    ("a[2..4] 每个 +2",      [(2, 4, 2)],             [3, 3, 6, 3, 5]),
    ("a[1..5] 每个 +10",     [(1, 5, 10)],            [13, 11, 14, 11, 15]),
    ("单点 a[3..3] +5",      [(3, 3, 5)],             [3, 1, 9, 1, 5]),
    ("一次都不改",            [],                      [3, 1, 4, 1, 5]),
    ("两次操作抵消一部分",    [(1, 2, 1), (4, 5, -1)], [4, 2, 4, 0, 4]),
]


def main():
    passed = 0
    for name, ops, want in CHECKS:
        try:
            d = build_diff(BASE, 5)
            for op in ops:
                range_add(d, *op)
            got = restore(d, 5)[1:]
            ok = (got == want)
        except Exception as e:
            got = f"{type(e).__name__}: {e}"
            ok = False

        print(f"  {'✓' if ok else '✗'} {name}")
        if not ok:
            print(f"      期望: {want}")
            print(f"      实际: {got}")
        passed += ok

    print(f"\n总计 {passed} / {len(CHECKS)}")
    if passed == len(CHECKS):
        print("\n模板记住了。下一步：做 2 道差分题（我出）。")
    else:
        print("\n先别往下走。第 4、5 个用例是专门用来抓「+= 写成 =」的。")


if __name__ == "__main__":
    main()
