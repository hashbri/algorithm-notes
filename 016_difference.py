# 016_difference.py —— 差分（2026-11-01 建）
#
# 差分是前缀和的"反面"：
#   前缀和：建表 O(n)，之后每次「问区间和」        O(1)
#   差分：  建表 O(n)，之后每次「区间每个数加 x」  O(1)，最后还原 O(n)
#
# 为什么需要它：
#   n 个数，m 次「把 a[l..r] 每个数加上 x」，最后输出整个数组。
#   暴力每次扫一遍区间 = O(n*m)，n = m = 10^5 时是 10^10 次操作，必超时。
#   差分把每次修改压到 O(1)，总复杂度 O(n + m)。
#
# 定义（一律 1 起编号，别混用 0 起）：
#   d[1] = a[1]
#   d[i] = a[i] - a[i-1]        (i >= 2)
#
# 你 10:40 自己推出来的两条，就是全部模板：
#   a[l..r] 每个加 x   →   d[l] += x   且   d[r+1] -= x
#
# ★ 唯一的坑：r = n 时 r+1 会越界 → d 必须开 n+2 个，多出来那个位置永不使用
#
# ------------------------------------------------------------
# 任务：把下面 3 处 ____ 填了，然后
#         python 016_difference.py
#       5 个用例全过，再往下做题。
# ------------------------------------------------------------


def build_diff(a, n):
    """由 a（1-indexed）造差分数组。返回长度 n+2。"""
    d = [0] * (n + 2)
    for i in range(1, n + 1):
        d[i] = a[i]-a[i-1]       # ← 空 1：d[i] 等于什么？
    return d


def range_add(d, l, r, x):
    """把 a[l..r] 每个数加上 x。只改 d，两行。"""
    d[l]+=x
    d[r+1]-=x


def restore(d, n):
    """由 d 还原 a（1-indexed，返回长度 n+1）。已写好，别改。"""
    a = [0] * (n + 1)
    cur = 0
    for i in range(1, n + 1):
        cur += d[i]
        a[i] = cur
    return a


