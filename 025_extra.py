# 025_extra.py —— 加练：把今天两件事合起来（2026-11-11 周三晚）
#
# 今天的两道题各教了一件事：
#   V1（最长递增段）= **分段**  —— 一个变量记当前段，一个记历史最好
#   V2（相邻差最大）= **记位置** —— 擂主被打赢时，值和位置要一起换
#
# 这道题把两件合起来：**分段 + 记位置**。
# 结果就是四个变量、两个"对子"：
#     当前段长  ↔  当前段从哪开始
#     历史最长  ↔  最长那段从哪开始
#
# 坑在哪儿：换段的时候，"当前段从哪开始"也要跟着归位。
# 只改长度不改起点，长度全对、位置全错 —— 而且不是每次都错。
#
# 用法：
#   python 025_extra.py

import io
import sys


# ======================================================================
# 题面
# ======================================================================
#
# 【题目】最长平台在哪
#
#   读入一行整数，找出「连续相同」最长的那一段，
#   输出它的**起始位置**（从 1 开始数）和**长度**，空格隔开。
#   如果有并列最长的，输出**第一次出现**的那一段。
#
# 【输入】一行整数
# 【输出】两个整数：起始位置、长度
#
# 【例】
#   1 1 2 2 2 3   →  3 3
#        ↑ 第 3 个数是第一个 2，这一段三个 2，长度 3
#
#   3 3 1 1 1     →  3 3
#        ↑ 最长的段在**末尾**，长度 3，从第 3 个数开始
#
#   1 2 3         →  1 1
#        ↑ 每段都只有 1 个，并列，取第一个
#
# 【提示】三个问题：
#   ① 你需要几个变量？分几组？每组记什么？
#   ② "当前段从哪开始"这个变量，什么时候要改？改成几？
#   ③ 并列最长时为什么不能更新？（这跟 V2 的哪个细节是同一个道理）
#
#   ⚠️ 不许用 max()，不许建列表。
#
# ----------------------------------------------------------------------
# 在下面的函数里写：
# ----------------------------------------------------------------------

def solve():
    data=list(map(int,input().split()))
    a=[0]+data
    c=1
    d=1
    best=1
    start=1
    for i in range(1,len(data)):
        if a[i]==a[i+1]:
            c+=1
        else:
            start=i+1
            if c>best:
                best=c
                d=start
            c=1
        if c>best:
            best=c
            d=start
    print(d,best)



# ======================================================================
# 自检（别改）
# ======================================================================

CHECKS = [
    ("1 1 2 2 2 3\n", "3 3"),      # 最长在中间
    ("3 3 1 1 1\n", "3 3"),        # 最长在末尾（只改长度不改起点就死在这）
    ("1 2 3\n", "1 1"),            # 全部并列，取第一个
    ("5\n", "1 1"),                # 单元素
    ("2 2 2 2\n", "1 4"),          # 从头到尾一段
    ("1 1 2 2\n", "1 2"),          # 并列最长，取第一次
    ("9 9 9 1 1 2\n", "1 3"),      # 最长在开头
]


def self_check():
    ok = 0
    for i, (fake_input, expected) in enumerate(CHECKS, 1):
        old_in, old_out = sys.stdin, sys.stdout
        sys.stdin = io.StringIO(fake_input)
        buf = io.StringIO()
        sys.stdout = buf
        err = None
        try:
            solve()
        except Exception as e:
            err = f"{type(e).__name__}: {e}"
        finally:
            sys.stdin, sys.stdout = old_in, old_out

        if err:
            print(f"  用例 {i}  x 报错 -> {err}")
            continue

        actual = buf.getvalue().replace("\r\n", "\n").rstrip("\n")
        exp = expected.rstrip("\n")
        if actual == exp:
            ok += 1
            print(f"  用例 {i}  ✓ 通过")
        else:
            print(f"  用例 {i}  ✗ 未过")
            print(f"       输入: {fake_input!r}")
            print(f"       期望: {exp!r}")
            print(f"       实际: {actual!r}")

    print()
    print(f"总计 {ok} / {len(CHECKS)}")


if __name__ == "__main__":
    self_check()
