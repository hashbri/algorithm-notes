def G():
    """
    【原型：G  C语言-最大值】

    题：输入 3 个实数，输出最大的那个数，保留 3 位小数，共输出两行。
        （原题说"用函数一次、用宏一次"—— 那是 C 的教学要求，
          Python 没有宏，你只要让两行输出一样就行。）
        样例输入：1 2 3
        样例输出：
            3.000
            3.000

    ── 提示 ──
        a, b, c = map(float, input().split())    ← 读小数用 float
        big = max(a, b, c)                       ← max 能直接吃三个数
        print(f"{big:.3f}")                      ← :.3f 保留 3 位小数
        print(f"{big:.3f}")

    ⚠️ int 读不了小数，会直接 ValueError。
    """
    a,b,c=map(float,input().split())
    result=max(a,b,c)
    print(f"{result:.3f}")
    print(f"{result:.3f}")



