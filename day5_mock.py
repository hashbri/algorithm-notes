def C():
    """
    【原型：C  C语言-数字交换】

    题：输入一行两个整数 a b，把它们交换后输出（空格分隔）。
        样例输入：3 5
        样例输出：5 3

    ── 提示（新知识，2 秒就能记住）──
        Python 交换两个变量不需要中间变量：
            a, b = b, a

        对比 C 语言（你要学的）：
            int t = a;  a = b;  b = t;      ← 得借一个临时变量

    ⚠️ 边界：两个数相等（0 0）、有负数（-1 7）都要能过。
    """
    a,b=map(int,input().split())
    a,b=b,a
    print(a,b)

