def H():
    """
    【原型：H  C语言-格式输出】

    题：输入一个整数 n（1 ≤ n ≤ 9），输出一个 n 行的星星金字塔。
        第 i 行 = (n-i) 个空格 + (2*i-1) 个星号。
        样例输入：3
        样例输出：
              *
             ***
            *****

    ── 提示（字符串乘法，很实用）──
        " " * 3   → "   "        空格重复 3 次
        "*" * 5   → "*****"

        所以第 i 行一行就够：
            print(" " * (n - i) + "*" * (2 * i - 1))

        外套一个 for i in range(1, n + 1) 即可。

    ⚠️ 这是"格式输出"的核心考点：【空格也是输出】。数错一个空格就是 WA。
       写完务必拿 n=1、n=2 手算一遍对不上。
    """
    n=int(input())
    for i in range(1,n+1):
        print(" "*(n-i)+"*"*(2*i-1))



