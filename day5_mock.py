def self_check(only=None):
    import io

    print("=" * 64)
    print("模拟卷自检：期望值 vs 实际输出")
    print("=" * 64)

    ok, total = 0, 0
    per_problem = {}
    for name, fake_input, expected in CHECKS:
        if only and name != only:
            continue
        total += 1
        per_problem.setdefault(name, [0, 0])
        per_problem[name][1] += 1

        func = globals().get(name)
        if func is None:
            print(f"  {name}  ✗ 函数不存在")
            continue

        old_stdin = sys.stdin
        sys.stdin = io.StringIO(fake_input)
        try:
            buf = io.StringIO()
            old_stdout = sys.stdout
            sys.stdout = buf
            try:
                func()
            finally:
                sys.stdout = old_stdout
            # 只去掉末尾换行，保留行首/行内空格 —— H 题靠空格拿分，不能被 strip 吃掉
            actual = buf.getvalue().replace("\r\n", "\n").rstrip("\n")
        except NotImplementedError:
            actual = "<还没写>"
        except Exception as e:
            actual = f"<报错: {type(e).__name__}: {e}>"
        finally:
            sys.stdin = old_stdin

        expected_norm = expected.rstrip("\n")
        passed = (actual == expected_norm)
        if passed:
            ok += 1
            per_problem[name][0] += 1
        print(f"  {name}  {'✓ 通过' if passed else '✗ 未过'}")
        if not passed:
            print(f"       输入: {fake_input!r}")
            print(f"       期望: {expected_norm!r}")
            print(f"       实际: {actual!r}")

    print("-" * 64)
    if per_problem:
        line = "  ".join(f"{k}:{v[0]}/{v[1]}" for k, v in per_problem.items())
        print("按题统计  " + line)
    print(f"通过 {ok} / {total}")

    # 分档统计：今天只看第一档
    if not only or only in TIER:
        print("-" * 64)
        for t in (1, 2, 3):
            names = [n for n in TIER_ORDER if TIER.get(n) == t]
            g_ok = sum(per_problem.get(n, [0, 0])[0] for n in names)
            g_all = sum(per_problem.get(n, [0, 0])[1] for n in names)
            if g_all == 0:
                continue
            if t == 1:
                verdict = "  ← ★ 今天的基础分，必须全绿" if g_ok == g_all else "  ← ★ 基础分有丢！优先补这个"
            elif t == 2:
                verdict = "  ← 有时间再上"
            else:
                verdict = "  ← 直接跳过，不用管"
            print(f"  {TIER_NAME[t]}  {' '.join(names)}  {g_ok}/{g_all}{verdict}")
    print("=" * 64)


if __name__ == "__main__":
    only = sys.argv[1].upper() if len(sys.argv) > 1 else None
    if only and only not in [c[0] for c in CHECKS]:
        print(f"没有这道题：{only}（可选：A B C D E F G H）")
        sys.exit(1)
    self_check(only)
