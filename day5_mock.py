def A():
    """
    【原型：A  C语言-报数】

    题：输入一个整数 n，输出 1 到 n，一行，每个数字后面跟一个空格。
        样例输入：5
        样例输出：1 2 3 4 5

    ── 提示（这是你还不会的那一类：循环输出）──
        for i in range(1, n + 1):     ← 注意是 n+1，range 左闭右开
            print(i, end=' ')         ← end=' ' 表示不换行、用空格接
        print()                       ← 最后补一个换行

        ★ 更省事的写法（推荐）：
            print(*range(1, n + 1))
          * 是"拆包"，把 range 里每个数拆成独立的参数丢给 print，
          print 默认就用空格隔开。

    ⚠️ range(1, n) 会少一个数；range(n) 会从 0 开始。
    """
    n=int(input())
    data=[]
    for i in range(1,n+1):
        data.append(i)
    print(*data)


