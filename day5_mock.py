def B():
    """
    【原型：B  C语言-数字调序】

    题：第一行一个整数 n，第二行 n 个整数。
        把它们按【从小到大】输出成一行，空格分隔。
        样例输入：
            5
            3 1 4 1 5
        样例输出：
            1 1 3 4 5

    ── 提示 ──
        这是你 Day2 练熟的东西：
            n = int(input())
            a = list(map(int, input().split()))
            a.sort()            # 或 sorted(a)
            print(*a)

    ⚠️ 第一行给了 n，代码里就用 n —— 别写死。
    """
    n=int(input())
    data=list(map(int,input().split()))
    data.sort()
    print(*data)

