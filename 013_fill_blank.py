# q2 · 10-29 四 · 双星数
# ============================================================
# 一个正整数，如果它转成二进制之后**恰好有 2 个 1**，就叫「双星数」。
# 例：3 → 11（两个 1，是）；5 → 101（两个 1，是）；7 → 111（三个 1，不是）
# 问：**不超过 2026** 的双星数一共有多少个？
#
# 我的答案：____ 个
#
# 思路提示（不是答案）：
#   - 程序部分不难：1 到 2026 挨个判断，数完拉倒。
#     判断"二进制里有几个 1"这一句自己写，别只写答案。
#   - 难点在手算那一遍。程序是"挨个数"，手算必须换一条路 ——
#     换成"按位数分类"。11 位的数最多能到 2047，比 2026 大，
#     所以 11 位这一类要单独处理。
@problem("q2")
def q2():
    res = 0
    for i in range(1, 2027):
        a = bin(i)[2:]
        if a.count("1") == 2:
            res += 1
    print(res)


