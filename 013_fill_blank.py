import sys

RUN = {}


def problem(name):
    def deco(fn):
        RUN[name] = fn
        return fn
    return deco


# ============================================================
# q1 · 10-22 四 · 读书计划
# ============================================================
# 小蓝买了一本共 2026 页的课外书，从周一开始连续阅读。
# 周一至周五每天最多读 5 页；周六周日每天最多读 15 页。
# 问：最少需要多少天才能完整读完？
#
# 我的答案：259 天
#
# 思路提示（不是答案）：
#   - 用 while 循环一天一天加，攒够 2026 页就停
#   - 用一个变量 day 记第几天，day % 7 判断星期几
#   - 关键：day % 7 的余数，哪一个对应周日？想清楚再写条件
@problem("q1")
def q1():
    data = 2026
    a, b = 5, 15
    day = 0
    page = 0
    while page < data:
        day += 1
        if day % 7 == 6 or day % 7 == 0:
            page += b
        else:
            page += a
    print(day)


