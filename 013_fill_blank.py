# q3 · 数位统计（填空，2026-11-12）
# ============================================================

# 【题目】
#   1 到 2026 这 2026 个整数里，数字 "1" 一共出现了多少次？
#
#   ⚠️ 不是"含 1 的数有几个"，是"1 这个字符一共出现几次"。
#      例：1~13 里，出现在 1 / 10 / 11（两次）/ 12 / 13 → 共 6 次
#
# 【要求】三步，缺一步不算过：
#   第一步：**手算**，用数位规律分区推，不许一个个数
#   第二步：**写代码暴力验证**（把 1..2026 拼成一个长字符串，数 '1'）
#   第三步：两个结果必须一致，一致才填答案；不一致就查是手算错还是代码错
#
# 【手算提示】
#   按位数分区，一块一块算：
#     1 ~ 999        一共有几个"1"？
#     1000 ~ 1999    千位上全是 1，这段跟上一段不一样
#     2000 ~ 2026    最后这一小段，只有 27 个数，可以精确数
#
#   每一区内，再分别看 个位 / 十位 / 百位 各贡献多少次。
#   （例：1~999 里，个位是 1 的数有 1,11,21,...,991 —— 共多少个？）
#
# 【答案】
#   手算：__1613______
#   代码：___1613_____
#   是否一致：__yes_____
# ------------------------------------------------------------

@problem("q3")
def q3():
    # 暴力统计：把 1..2026 全部拼成一个长字符串，数其中 '1' 的个数
    a=''.join(str(i) for i in range(1,2027))
    res=a.count('1')
    print(res)


