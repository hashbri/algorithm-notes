CHECKS = [
    # ---- P1 词频统计 ----
    ("P1", "3 5\n4 1 2 3 2\n3 2 4 2\n2 1 5\n",
           "2 2\n2 4\n1 1\n1 1\n1 1"),
    ("P1", "1 3\n3 1 1 1\n",
           "1 3\n0 0\n0 0"),
    ("P1", "2 4\n1 1\n1 1\n",
           "2 2\n0 0\n0 0\n0 0"),
    ("P1", "2 3\n3 1 1 1\n3 1 1 1\n",
           "2 6\n0 0\n0 0"),

    # ---- P2 平衡数 ----
    ("P2", "4\n12 10 7 3\n", "2"),
    ("P2", "1\n1\n", "0"),
    ("P2", "5\n1 2 3 4 5\n", "1"),
    ("P2", "5\n8 9 10 12 15\n", "3"),

    # ---- P3 仓库规划 ----
    ("P3", "3 3\n0 0 0\n1 1 1\n0 1 0\n", "2\n0\n0"),
    ("P3", "2 2\n0 0\n1 1\n", "2\n0"),
    ("P3", "3 2\n1 1\n2 2\n0 0\n", "2\n0\n1"),
    ("P3", "3 3\n2 2 2\n1 1 1\n3 3 3\n", "3\n1\n0"),
]


def self_check(only=None):
    total = 0
    ok = 0
    per = {}
    for name, fake_input, expected in CHECKS:
        if only and name != only:
            continue
        total += 1
        old_stdin, old_stdout = sys.stdin, sys.stdout
        sys.stdin = io.StringIO(fake_input)
        buf = io.StringIO()
        sys.stdout = buf
        err = None
        try:
            FUNCS[name]()
        except Exception as e:
            err = f"{type(e).__name__}: {e}"
        finally:
            sys.stdin, sys.stdout = old_stdin, old_stdout

        if err:
            print(f"  {name}  x 报错 -> {err}")
            continue

        # 只去末尾换行，行首空格必须保留（格式题全靠它）
        actual = buf.getvalue().replace("\r\n", "\n").rstrip("\n")
        exp = expected.rstrip("\n")
        if actual == exp:
            ok += 1
            per[name] = per.get(name, 0) + 1
            print(f"  {name}  ✓ 通过")
        else:
            print(f"  {name}  ✗ 未过")
            print(f"       输入: {fake_input!r}")
            print(f"       期望: {exp!r}")
            print(f"       实际: {actual!r}")

    print()
    print(f"总计 {ok} / {total}")
    for name in ("P1", "P2", "P3"):
        if not only or name == only:
            cnt = sum(1 for c in CHECKS if c[0] == name and (not only or c[0] == only))
            print(f"  {name}  {per.get(name, 0)} / {cnt}")
    print()
    print("顺序建议：P1 先做（零新知识）→ P2（多一个 bin）→ P3（要多想一层）")


if __name__ == "__main__":
    only = sys.argv[1] if len(sys.argv) > 1 else None
    self_check(only)
