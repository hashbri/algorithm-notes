# Q3 · 字符分类统计
# 【题面】读入一行字符串，统计里面字母、数字、其他字符各有多少个。
# 【输入】一行字符串（不含空格）
# 【输出】三行，依次是：字母个数、数字个数、其他字符个数
# 【提示】ch.isalpha() 判断字母，ch.isdigit() 判断数字，
#        剩下的是其他 —— 三分支，想想用 if/elif/else 怎么排。
@problem("Q3")
def Q3():
    data=input()
    a,b,c=0,0,0
    for i in data:
        if i.isalpha():
            a+=1
        elif i.isdigit():
            b+=1
        else:
            c+=1
    print(a)
    print(b)
    print(c)



