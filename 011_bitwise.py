# Q6 · 3 或 5 的倍数   （蓝桥杯填空题风格）
# 【题面】1 ~ n 中有多少个数能被 3 或 5 整除？
# 【输入】一行，整数 n
# 【输出】一个整数
# 【提示】⚠️ range(1, n+1) —— 右开，你在这里漏过最后一个数。
#        "能被 3 或 5" 是一个 or，别写成 and。
@problem("Q6")
def Q6():
    n=int(input())
    a=0
    for i in range(1,n+1):
        if i%3==0 or i%5==0:
            a+=1
    print(a)




