# Q4 · 回文判断
# 【题面】读入一行字符串，如果正着读和倒着读一样，输出 YES，否则 NO。
# 【输入】一行字符串
# 【输出】YES 或 NO（全大写）
# 【提示】切片可以倒着走：s[::-1] 就是反转后的字符串。
#        注意：单字符也是回文。
@problem("Q4")
def Q4():
    data=input()
    data_=data[::-1]
    if data==data_:
        print("YES")
    else:
        print("NO")



