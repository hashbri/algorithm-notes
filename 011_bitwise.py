# Q8 · 第一个比 x 大的   （二分下界模板 · 变体）
# 【题面】给出 n 个升序整数和一个 x，输出第一个【严格大于 x】的数的下标
#        （从 0 开始）。如果没有，输出 -1。
# 【输入】第 1 行：n；第 2 行：n 个升序整数；第 3 行：x
# 【输出】一个整数（下标或 -1）
# 【提示】这就是 006_binary_search.py 的"下界模板"，只是把 >= 换成 > ：
#           第一个 >= x 用  data[mid] < x  → left = mid + 1
#           第一个 >  x 用  data[mid] <= x → left = mid + 1
#        循环结束后 left 就是答案位置；如果 left == n 说明没有。
#        ⚠️ 输入有 3 行，第 3 行的 x 别忘了读。
@problem("Q8")
def Q8():
    n=int(input())
    data=list(map(int,input().split()))
    x=int(input())
    left,right=0,n
    while left<right:
        mid=(left+right)//2
        if x>=data[mid]:
            left=mid+1
        else:
            right=mid
    if left==n:
        print(-1)
    else:
        print(left)



