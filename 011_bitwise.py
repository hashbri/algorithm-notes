# ----------------------------------------------------------------------
# Q1 · 第二大的数
# 【题面】给出 n 个整数（可能有重复），输出其中"第二大的值"。
#        如果所有数都相同（不足 2 个不同的值），输出 -1。
# 【输入】第 1 行：n；第 2 行：n 个整数
# 【输出】一个整数
# 【提示】"去重 + 排序"之后，第二大的是倒数第 2 个。
#        ⚠️ 写完问自己：sorted(...) 的返回值你去哪儿了？
@problem("Q1")
def Q1():
    n=int(input())
    data=list(map(int,input().split()))
    a=sorted(set(data))
    if len(a)==1:
        print(-1)
    else:
        print(a[-2])


# ----------------------------------------------------------------------
# Q2 · 比平均分高的有几个
# 【题面】给出 n 个整数，统计其中"严格大于平均值"的个数。
# 【输入】第 1 行：n；第 2 行：n 个整数
# 【输出】一个整数（可能是 0）
# 【提示】平均值 = sum / n，是浮点数，直接拿来比较没问题。
#        注意是"严格大于"，不是"大于等于"。
@problem("Q2")
def Q2():
    n=int(input())
    data=list(map(int,input().split()))
    a=sum(data)/n
    pos=0
    for i in data:
        if i>a:
            pos+=1
    print(pos)







