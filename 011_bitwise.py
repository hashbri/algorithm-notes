# Q7 · 数位平方和，迭代 10 次
# 【题面】读入一个正整数 x。每次操作：把 x 替换成"它各数位的平方和"。
#        例如 19 → 1²+9²=82 → 8²+2²=68 → 6²+8²=100 → 1²+0²+0²=1 → 1 → ...
#        （⚠️ 每一步都是拆【当前这个数】的各位，不是拆上一次的结果）
#        输出第 10 次操作之后的结果。
# 【输入】一行，正整数 x
# 【输出】一个整数
# 【提示】str(x) 可以逐位遍历；每一位是字符，要 int() 转回来。
#        每次循环结束，x 要更新成新值 —— 别忘记赋值方向。
@problem("Q7")
def Q7():
    x=int(input())
    for i in range(10):
        s=0
        for ch in str(x):
            s=s+int(ch)**2
        x=s
    print(x)




