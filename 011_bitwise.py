    # ---- Q3 字符分类统计 ----
    ("Q3", "abc123\n", "3\n3\n0"),
    ("Q3", "a1!b2@\n", "2\n2\n2"),
    ("Q3", "2026\n", "0\n4\n0"),

    # ---- Q4 回文判断 ----
    ("Q4", "level\n", "YES"),
