# Q5 · 最长的单词
# 【题面】读入一行单词（空格分隔），输出最长的那个。
#        如果有并列最长，输出排最前面的那个。
# 【输入】一行单词
# 【输出】一个单词
# 【提示】先 split() 成列表，然后"打擂台"：记住目前最长的，
#        遇到更长的才换。并列不换 —— 想想该用 > 还是 >=。
@problem("Q5")
def Q5():
    data=input().split()
    win=data[0]
    for i in data:
        if len(i)>len(win):
            win=i
    print(win)



