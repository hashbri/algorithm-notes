# T2 · 原地去重（快慢指针）
# ======================================================================
# 【题面】
#   给一个**已经升序排好的**数组，里面可能有连续重复的值。
#   要求把重复的去掉，**结果仍然存在这个数组本身里**（不新建列表）。
#
#   最后输出：
#     第 1 行：去重后还剩几个数（记作 k）
#     第 2 行：数组的前 k 个位置（也就是去重后的结果，空格隔开）
#
# 【输入】
#   第 1 行：n
#   第 2 行：n 个整数（升序，可能重复）
#
# 【输出】两行，见上
#
# 【例】
#   6
#   1 2 3 3 3 3
#   →
#   3
#   1 2 3
#
# 【硬要求】（这题全部的分都在硬要求上）
#   1. **不许新建列表装结果** —— 不许 `[]` 再 append、不许 `list(set(a))`、
#      不许 `sorted(set(a))`。只能用下标去**改原来那个 a**。
#   2. **单层循环**，i 从 0 走到 n-1，只走一遍。
#   3. 不许用 `set` 这个类型出现在代码里。
#
# 【提示】想清楚这三件事再动手：
#   ① 这题有两个"指针"，但它们的**分工不一样**：
#      一个负责**往后扫描看新东西**（叫 fast），
#      一个负责**记录"已经写好的结果"的末尾在哪**（叫 slow）。
#      哪一个是"只增不减"的那个？
#   ② 扫描指针看到 a[fast] 时，它该跟**谁**比 —— 跟上一次值比，还是跟
#      已写好结果的最后一个比？两个都写得出来，但有一个更稳，想想为什么。
#   ③ 边界：全是同一个数（k=1）、一个数都没有重复（k=n）、只有 n=1。
#
#   ⚠️ 这题最容易错的地方：**最后那个元素**。当扫描指针走到末尾、
#      刚好发现一个新值时，你有没有把它写进去？用 `1 2 3 4 4` 试。
#
# 【提醒】你的老毛病 #1 是"返回值没接住"。这题里 `a[k] = a[i]` 这种
#   赋值是**直接改原数组**，不需要接返回值，别在这上面绕。
@problem("T2")
def T2():
    n=int(input())
    a=list(map(int,input().split()))
    # TODO: 你来写
    #   用 i 扫描、用 k 记录"已写好结果的末尾（下一个该写的位置）"
    #   最后 print(k) 和 print(*a[:k])
    i,k=0,0
    while i<n-1:
        i+=1
        if a[k]!=a[i]:
            k+=1
            a[k]=a[i]

    print(k+1)
    print(*a[:k+1])
    return


