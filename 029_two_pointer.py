# T4 · 长度为 k 的连续子数组最大和（定长窗口）
# ======================================================================
# 【题面】
#   给 n 个整数和一个 k。在所有**长度为 k 的连续段**里，找出和最大的那一个，
#   输出这个最大的和（只输出和，不用输出是哪一段）。
#
# 【输入】
#   第 1 行：n k   （保证 1 ≤ k ≤ n）
#   第 2 行：n 个整数（**可能有负数**）
#
# 【输出】一个整数
#
# 【例】
#   6 3
#   1 3 -1 4 -2 6
#   →  8
#      （四段分别是 3、6、1、8，最大 8，对应 4 -2 6）
#
# 【硬要求】
#   1. **不许在循环里写 `sum(a[i:i+k])`** —— 那是 O(n·k)，n=10^5 时直接超时
#   2. 必须滑动窗口：整体只走一遍，**每移动一格只做「进一个、出一个」两件事**
#   3. 第一段的和可以单独算（那一次 O(k) 是允许的），之后每格必须是 O(1)
#
# 【提示】这题的所有东西就看一张图：
#
#      ...  [ a[i-k] | ...窗口... ]  a[i]  ...
#            ↑ 马上要滑出去          ↑ 马上要滑进来
#
#   窗口往右移一格，**出去的是谁、进来的是谁**？用下标怎么表示？
#   想清楚这个，代码就只有三行。
#
# 【坑】
#   ① **最后一段**有没有被算进去？（循环的终点是 n 还是 n-1？）
#   ② **全是负数**的时候，你的 `best` 初值取 0 会不会直接错？
#      —— 想想上一周 R7 那题 ±inf 的教训。
#   ③ k=1 和 k=n 这两种极端。
@problem("T4")
def T4():
    n,k=map(int,input().split())
    a=list(map(int,input().split()))
    # TODO: 你来写
    #   先算第一段的和 s（这一段 O(k) 允许），best = s
    #   然后 i 从 k 走到 n-1：s 加上进来的、减掉出去的，再打擂台
    sum_k=0

    for x in range(k):
        sum_k+=a[x]
    best = sum_k
    for i in range(k,n):
        sum_k+=a[i]-a[i-k]
        if sum_k>best:
            best=sum_k
    print(best)
    return


