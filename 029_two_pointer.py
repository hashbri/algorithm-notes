# T5 · 和 ≥ target 的最短连续子数组（变长窗口 / 伸缩窗口）
# ======================================================================
# 【题面】
#   给 n 个**正整数**和一个 target。找一个**连续段**，让它的和 **≥ target**，
#   并且这个连续段要**尽可能短**。输出最短的长度。
#   如果整段加起来都到不了 target，输出 0。
#
# 【输入】
#   第 1 行：n target
#   第 2 行：n 个正整数
#
# 【输出】一个整数（最短长度，或 0）
#
# 【例】
#   6 7
#   2 3 1 2 4 3
#   →  2
#      （2+3+1+2=8 长度 4，但 4+3=7 长度只有 2，还有 3+1+2+4=10 更长）
#
# 【硬要求】
#   1. **必须滑动窗口**：一个端点从左扫到右（只走 n 步），另一个端点**只增不减**
#   2. **不许双层 for**（"每个起点都重新往右扫"是 O(n²)，超时）
#   3. 全程 O(n)
#
# 【提示】
#   ① 这题和前四题都不一样：**窗口长度是变的**。所以不能"进一个出一个"，
#      而是分两个动作：
#        - 和**不够** target → 扩（右端往右吃一个数）
#        - 和**够了**       → 缩（记下当前长度打擂台，然后左端往右吐一个数）
#      **"够了就缩"这个动作，要一直缩到不够为止**，所以里面是个 while。
#   ② 想想为什么题目必须写"**正**整数"。
#      如果允许负数，会不会出现"缩了一个数，和反而变大"？
#      一旦出现这种情况，"缩"就失去了方向 —— 这题就废了。
#      ★ 这就是双指针的命门：**它吃的是单调性**。
#   ③ 收缩的顺序：**先减 `a[l]`，再 `l+=1`**。顺序反了会减错元素。
#
# 【坑】
#   ① 找不到答案时输出 **0**，不是 -1，也不是一个很大的数。
#      所以要问自己：**用来记"最短长度"的那个变量，初值取多少，
#      才不会把"根本没找到"这种情况当成一个有效答案？**
#      （想不出就用一个必然比任何真实长度都大的初值，最后再判一次）
#   ② **整段才够**的情况（和正好等于 target）。
#   ③ n=1。
#   ④ 如果只扩不缩，样例会答 4 —— 用例已经放好，别想蒙过去。
@problem("T5")
def T5():
    n,target=map(int,input().split())
    a=list(map(int,input().split()))
    # ← 从这里开始，白纸。没有骨架，自己想变量和结构。
    i=0
    sum_a=0
    min_a=n+1
    for j in range(n):
        sum_a+=a[j]
        while sum_a>=target:
            res=j-i+1
            if res<min_a:
                min_a=res
            sum_a-=a[i]
            i+=1
    if min_a==n+1:
        min_a=0
    print(min_a)
    return



