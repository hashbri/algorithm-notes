# T3 · 判断回文串（对撞指针 + 跳过空格）
# ======================================================================
# 【题面】
#   给一行字符串，判断它是不是回文串。
#   判定规则：**忽略空格、不区分大小写**，剩下的字符从两端往中间读要一样。
#
# 【输入】一整行字符串（可能**含空格**），长度 ≥ 1
#
# 【输出】YES 或 NO
#
# 【例】
#   A man a plan a canal Panama   →  YES
#      （去掉空格变 amanaplanacanalpanama，正着读反着读一样）
#
#   hello                          →  NO
#
# 【硬要求】
#   1. **必须用对撞指针**：i 从左、j 从右，往中间走
#   2. **不许用 `s[::-1]`**，也不许 `s == s[::-1]`
#   3. **不许先造一个新的干净字符串**再比 —— 不许 `''.join(...)`、
#      不许 `s.replace(' ','')`、不许 `[c for c in s if c!=' ']`。
#      只能在**原来那个字符串**上用下标走。
#
# 【提示】
#   ① 读到含空格的整行，用 `input()`。⚠️ 千万别 `input().split()` ——
#      那会按空格切成一堆碎片，字符串就没了。这是 IO 的老坑。
#   ② 移动的时候，i 和 j **不一定每次各走一步**。碰到空格怎么办？
#      这就是"指针可以单独多走几步"的第一次出现。
#   ③ 什么时候可以直接判 YES？i 和 j 撞上了（或者越过了）说明中间没矛盾。
#   ④ 边界：只有 1 个字符、只有 1 个空格、全是空格、两个字符。
#
# 【提醒】这题最容易出的错不是算法，是**大小写**：`'A' != 'a'`。
#   比较的那一刻要把两边都转成同一种大小写，别在循环外面转（因为外面
#   那一整串还没过滤，转了也没用）。
@problem("T3")
def T3():
    s=input()
    # TODO: 你来写
    #   i,j = 0, len(s)-1 ; res = "YES"
    #   while i<j: 跳过空格 → 比大小写 → 不一样就 res="NO" break
    #   最后 print(res)
    a=list(s)
    i,j=0,len(s)-1
    res="YES"
    while i<j:
        while i<j and a[i]==' ':
            i+=1
        while i<j and a[j]==' ':
            j-=1
        if a[i].lower()==a[j].lower():
            i+=1
            j-=1
        else:
            res="NO"
            break
    print(res)

    return


