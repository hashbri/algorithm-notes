# T1 · 两数之和（数组已升序排序）
# ======================================================================
# 【题面】
#   给一个**已经从小到大的**数组，和一个目标值 target。
#   找出两个数，使它们相加正好等于 target，输出这两个数（小的在前，空格隔开）。
#
#   如果有多组解，输出**先找到的那一组**（也就是 i 最小的那组）。
#   如果没有任何一组，输出 NO。
#
# 【输入】
#   第 1 行：n target
#   第 2 行：n 个整数（已升序排序，可能有重复）
#
# 【输出】两个数 或 NO
#
# 【例】
#   5 13
#   1 3 5 8 11        →  5 8
#
#   3 10
#   1 2 3             →  NO
#
# 【硬要求】
#   1. **必须用对撞指针**（i 从左边、j 从右边，往中间走）
#   2. **不许双层 for 循环** —— 用了就算过也记 0 分
#   3. 一层 while（或 for），比较次数要接近 n 次，不是 n^2 次
#
# 【提示】想清楚三件事再动手：
#   ① i 和 j 的初值分别是什么？
#   ② 当 a[i] + a[j] **小于** target 时，该动谁？为什么动它不是动另一个？
#   ③ 当它们**大于** target 时，又该动谁？
#      —— 这条推理要用到"数组已经排好序"这件事，说不出理由就是没懂。
#
#   ⚠️ 边界：n 可能只有 1 个（此时不可能凑出两个数）。
@problem("T1")
def T1():
    n,target=map(int,input().split())
    a=list(map(int,input().split()))
    i,j=0,n-1
    res="NO"
    while i<j:
        if a[i]+a[j]<target:
            i+=1
        elif a[i]+a[j]>target:
            j-=1
        else:
            res=f"{a[i]} {a[j]}"
            break
    print(res)


