# 【为什么补这题】
# 020 那道"行和 + 总和"是废题：可以一边读一边算完（每行 sum 一下就扔），
# 矩阵从头到尾没起作用 —— 存储、双下标访问、初始化坑，三样一个都没练到。
# 判断一道题是否真需要二维数组，标准只有一条：
#   **能不能一边读一边算完？** 能 → 不需要矩阵；不能 → 必须存。
#
# 转置属于"不能"：输入按行给，输出按列排，读完最后一行之前
# 你根本不知道该往哪一列写。所以必须先把整个矩阵存下来。
#
# 这题一次练三样：
#   ① 预分配一个矩阵（并且行列数要跟原矩阵**反过来**）
#   ② 双下标读写 a[i][j] → b[?][?]
#   ③ 初始化陷阱：[[0]*n]*m 会让所有行指向同一个列表，改一格全毁
#
# 用法：
#   python 026_matrix_transpose.py


import io
import sys


# ======================================================================
# 题面
# ======================================================================
#
# 【题目】矩阵转置
#
#   读入一个 n 行 m 列的矩阵，输出它的转置：
#   把原矩阵的第 i 行变成新矩阵的第 i 列。
#
# 【输入】
#   第 1 行：n m
#   接下来 n 行：每行 m 个整数（空格分隔）
#
# 【输出】m 行，每行 n 个整数（空格分隔）
#
# 【样例】
#   输入            输出
#   2 3             1 4
#   1 2 3           2 5
#   4 5 6           3 6
#
#   （原来 2 行 3 列，转置后 3 行 2 列）
#
# 【硬要求】
#   1. **必须先建一个新矩阵装转置结果，再按行输出。**
#      不许用 for j: for i: print(...) 直接按列打印 —— 那样练不到写入。
#   2. 新矩阵的行列数是多少？想清楚再写（很容易直接抄成 n 行 m 列）。
#   3. 新矩阵要**预先分配好**（用列表推导式），因为你写入的顺序是乱的。
#
# 【提示】
#   ① 原矩阵 a 是 n 行 m 列。转置后是 m 行 n 列。
#   ② a[i][j] 应该搬到 b 的哪个格子？
#     用一句话说：原矩阵"第 i 行第 j 列"，转置后变成"第几行第几列"？
#   ③ 双层循环，外层走 i、内层走 j，还是反过来？两种都行，想清楚再写。
#
# ----------------------------------------------------------------------
# 在下面的函数里写：
# ----------------------------------------------------------------------

def solve():
    n,m=map(int,input().split())
    a=[]
    for i in range(n):
        b=list(map(int,input().split()))
        a.append(b)
    c=[[0]*n for _ in range(m)]
    for i in range(n):
        for j in range(m):
            c[j][i]=a[i][j]
    for line in c:
        print(*line)




